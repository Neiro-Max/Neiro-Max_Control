@dataclass(frozen=True)
class ProjectSpec:
    project_id: int
    name: str
    description: str
    project_type: str


def _clean(value: str) -> str:
    return " ".join((value or "").replace("\n", " ").split()).strip()


def _website_title(spec: ProjectSpec) -> str:
    text = _clean(spec.description)
    patterns = [
        r"(?:с заголовком|заголовок)\s+[«\"']?(.+?)[»\"']?$",
        r"(?:под названием|название)\s+[«\"']?(.+?)[»\"']?$",
    ]
    for pattern in patterns:
        match = re.search(pattern, text, flags=re.IGNORECASE)
        if match:
            candidate = match.group(1).strip(" .,!?:;\"'«»")
            if candidate:
                return candidate[:80]

    lowered = text.lower()
    for prefix in ("создай сайт для ", "сделай сайт для ", "создай лендинг для ", "сделай лендинг для "):
        if lowered.startswith(prefix):
            candidate = text[len(prefix):].strip(" .,!?:;\"'«»")
            if candidate:
                return candidate[:80]

    title = _clean(spec.name)
    return (title or f"Project {spec.project_id}")[:80]


