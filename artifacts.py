from __future__ import annotations

from dataclasses import dataclass
from typing import Dict


@dataclass(frozen=True)
class ProjectSpec:
    project_id: int
    name: str
    description: str
    project_type: str


def build_artifacts(spec: ProjectSpec) -> Dict[str, str]:
    title = spec.name.replace("\n", " ").strip() or f"Project {spec.project_id}"
    description = spec.description.replace("\n", " ").strip()

    if spec.project_type == "bot":
        return {
            "requirements.txt": "python-telegram-bot>=21,<22\n",
            "bot.py": (
                "import os\n"
                "from telegram import Update\n"
                "from telegram.ext import Application, CommandHandler, ContextTypes\n\n"
                "async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):\n"
                "    await update.message.reply_text('Здравствуйте! Бот готов к настройке.')\n\n"
                "def create_application():\n"
                "    token = os.environ.get('BOT_TOKEN')\n"
                "    if not token:\n"
                "        raise RuntimeError('BOT_TOKEN is not configured')\n"
                "    app = Application.builder().token(token).build()\n"
                "    app.add_handler(CommandHandler('start', start))\n"
                "    return app\n\n"
                "if __name__ == '__main__':\n"
                "    create_application().run_polling()\n"
            ),
            "README.md": f"# {title}\n\n{description}\n\nGenerated by NEIRO MAX CONTROL.\n",
        }

    if spec.project_type == "website":
        return {
            "index.html": (
                "<!doctype html><html lang='ru'><head><meta charset='utf-8'>"
                "<meta name='viewport' content='width=device-width,initial-scale=1'>"
                f"<title>{title}</title><link rel='stylesheet' href='styles.css'></head>"
                f"<body><main><h1>{title}</h1><p>{description}</p></main></body></html>"
            ),
            "styles.css": (
                "body{font-family:Arial,sans-serif;max-width:960px;margin:60px auto;"
                "padding:0 24px;background:#0d1117;color:#f4f7fb}h1{font-size:42px}"
            ),
            "server.py": (
                "import os\n"
                "from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler\n\n"
                "port = int(os.environ.get('PORT', '8000'))\n"
                "ThreadingHTTPServer(('0.0.0.0', port), SimpleHTTPRequestHandler).serve_forever()\n"
            ),
            "README.md": f"# {title}\n\n{description}\n\nGenerated by NEIRO MAX CONTROL.\n",
        }

    return {"README.md": f"# {title}\n\n{description}\n\nGenerated by NEIRO MAX CONTROL.\n"}
